def get_neighbors(state):
    """Generates valid adjacent states by moving the blank tile (0) UP, DOWN, LEFT, or RIGHT."""
    neighbors = []
    blank_idx = state.index(0)
    row, col = divmod(blank_idx, 3)

    moves = {
        "UP": (row - 1, col),
        "DOWN": (row + 1, col),
        "LEFT": (row, col - 1),
        "RIGHT": (row, col + 1)
    }

    for move_name, (next_row, next_col) in moves.items():
        if 0 <= next_row < 3 and 0 <= next_col < 3:
            new_blank_idx = next_row * 3 + next_col
            new_state = list(state)
            new_state[blank_idx], new_state[new_blank_idx] = new_state[new_blank_idx], new_state[blank_idx]
            neighbors.append((tuple(new_state), move_name))

    return neighbors

def dls_solve(current_state, goal_state, limit, path, visited):
    """Solves the 8-puzzle using Depth Limited Search (DLS)."""
    # Base case: Goal reached
    if current_state == goal_state:
        return path

    # Base case: Depth bound reached
    if limit <= 0:
        return "CUTOFF"  # Reached limit without finding target

    cutoff_occurred = False

    for neighbor, move in get_neighbors(current_state):
        if neighbor not in visited:
            visited.add(neighbor)

            # Recursively search down with a decremented depth limit boundary
            result = dls_solve(neighbor, goal_state, limit - 1, path + [move], visited)

            visited.remove(neighbor)  # Backtracking step

            if result == "CUTOFF":
                cutoff_occurred = True
            elif result is not None:
                return result

    return "CUTOFF" if cutoff_occurred else None

def take_input(state_name):
    """Takes input row-by-row and strictly validates exactly 3 numbers per row."""
    print(f"\n--- Enter values for the {state_name} (Use 0 for the blank space) ---")
