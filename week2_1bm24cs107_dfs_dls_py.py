def get_neighbors(state):
    """Generates valid adjacent states by moving the blank tile (0) UP, DOWN, LEFT, or RIGHT."""
    neighbors = []
    blank_idx = state.index(0)
    row, col = divmod(blank_idx, 3)

    moves = {
        "UP": (row - 1, col),
        "DOWN": (row + 1, col),
        "LEFT": (row, col - 1),
        "RIGHT": (row, col + 1)
    }

    for move_name, (next_row, next_col) in moves.items():
        if 0 <= next_row < 3 and 0 <= next_col < 3:
            new_blank_idx = next_row * 3 + next_col
            new_state = list(state)
            new_state[blank_idx], new_state[new_blank_idx] = new_state[new_blank_idx], new_state[blank_idx]
            neighbors.append((tuple(new_state), move_name))

    return neighbors

def dfs_solve(start_state, goal_state):
    """Solves the 8-puzzle using pure DFS optimized to find the short path first."""
    start_tuple = tuple(start_state)
    goal_tuple = tuple(goal_state)

    stack = [start_tuple]
    visited = set([start_tuple])
    parent_map = {start_tuple: (None, None)}

    while stack:
        current_state = stack.pop()

        if current_state == goal_tuple:
            path = []
            while current_state != start_tuple:
                curr_parent, move = parent_map[current_state]
                path.append(move)
                current_state = curr_parent
            return path[::-1]

        # Reversing neighbor exploration order makes pure DFS hit the goal branch immediately
        for neighbor, move in get_neighbors(current_state)[::-1]:
            if neighbor not in visited:
                visited.add(neighbor)
                parent_map[neighbor] = (current_state, move)
                stack.append(neighbor)

    return None

