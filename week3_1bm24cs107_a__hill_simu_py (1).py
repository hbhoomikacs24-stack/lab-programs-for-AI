import itertools

def get_attacking_pairs(state):
    """
    Cost Function: Counts the number of pairs of queens attacking each other
    directly or indirectly (checks rows and diagonals).
    """
    attacks = 0
    n = len(state)
    for i in range(n):
        for j in range(i + 1, n):
            # Same row attack
            if state[i] == state[j]:
                attacks += 1
            # Diagonal attack: row difference == column difference
            elif abs(state[i] - state[j]) == abs(i - j):
                attacks += 1
    return attacks

def get_best_neighbor(state):
    """
    Neighbor Generation: Swaps the row positions of two queens.
    Enforces the tie-breaking rule using sorted column indices (i, j).
    """
    n = len(state)
    best_state = None
    min_cost = float('inf')
    best_swap_indices = (float('inf'), float('inf'))

    print("\n--- Generating and evaluating all swap neighbors ---")

    # Generate pairs of columns to swap (i, j) where i < j
    # This automatically processes pairs in order of smallest subscripts first
    for i, j in itertools.combinations(range(n), 2):
        # Create neighbor state by swapping values at index i and j
        neighbor = list(state)
        neighbor[i], neighbor[j] = neighbor[j], neighbor[i]

        cost = get_attacking_pairs(neighbor)
        print(f"Swap columns ({i}, {j}) -> Neighbor State: {neighbor} | Cost: {cost}")

        # Check if this neighbor is strictly better or resolves a tie-breaker
        if cost < min_cost:
            min_cost = cost
            best_state = neighbor
            best_swap_indices = (i, j)
        elif cost == min_cost:
            # If cost is tied, pick the one with smaller subscripts (i, j lexicographically)
            if (i, j) < best_swap_indices:
                best_state = neighbor
                best_swap_indices = (i, j)

    return best_state, min_cost, best_swap_indices

def print_board(state):
    """Helper to visualize the 4x4 chessboard configurations"""
    n = len(state)
    for row in range(n):
        line = ""
        for col in range(n):
            if state[col] == row:
                line += " Q "
            else:
                line += " . "
        print(line)
    print()

def hill_climbing_4_queens(initial_state):
    """Core Hill Climbing algorithm execution block"""
    current_state = list(initial_state)
    current_cost = get_attacking_pairs(current_state)

    step = 0
    print("==================================================")
    print("🚀 STARTING HILL CLIMBING (4-QUEENS)")
    print("==================================================")
    print(f"Step {step} (Initial State): {current_state} | Cost: {current_cost}")
    print_board(current_state)

    while True:
        # Fetch the optimal candidate from neighboring mutations
        neighbor_state, neighbor_cost, swap_used = get_best_neighbor(current_state)

        # Terminate search if neighbor cost doesn't strictly improve over current value
        if neighbor_cost >= current_cost:
            print("\n==================================================")
            if current_cost == 0:
                print("🎉 SUCCESS: Global optimum goal state discovered!")
            else:
                print("🛑 TERMINATED: Hit local maxima/plateau. No strict improvements available.")
            print("==================================================")
            print(f"Final State Configuration: {current_state} with final cost: {current_cost}")
            print_board(current_state)
            break

        # Move up the gradient to the superior neighboring state
        step += 1
        current_state = neighbor_state
        current_cost = neighbor_cost

        print(f"\n➔ Step {step}: Selected swap {swap_used} -> State: {current_state} | Cost: {current_cost}")
        print_board(current_state)

