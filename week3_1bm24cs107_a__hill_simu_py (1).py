import heapq

class PuzzleState:
    def __init__(self, board, g=0, parent=None, action="Initial"):
        self.board = tuple(board)
        self.g = g  # Path cost (depth)
        self.parent = parent
        self.action = action
        self.h = 0  # Heuristic value

    @property
    def f(self):
        return self.g + self.h

    def __lt__(self, other):
        return self.f < other.f

    def get_blank_pos(self):
        idx = self.board.index(0)
        return idx // 3, idx % 3

    def get_neighbors(self):
        neighbors = []
        r, c = self.get_blank_pos()
        moves = {
            "Up": (r - 1, c),
            "Down": (r + 1, c),
            "Left": (r, c - 1),
            "Right": (r, c + 1)
        }

        for action, (nr, nc) in moves.items():
            if 0 <= nr < 3 and 0 <= nc < 3:
                new_blank_idx = nr * 3 + nc
                old_blank_idx = r * 3 + c

                new_board = list(self.board)
                new_board[old_blank_idx], new_board[new_blank_idx] = new_board[new_blank_idx], new_board[old_blank_idx]

                neighbors.append(PuzzleState(new_board, self.g + 1, self, action))
        return neighbors

    def print_board(self):
        for i in range(0, 9, 3):
            row = [str(x) if x != 0 else "_" for x in self.board[i:i+3]]
            print(" ".join(row))
        print()

# Heuristic: Count of misplaced tiles (excluding the blank space)
def heuristic_misplaced_tiles(board, goal_board):
    count = 0
    for i in range(len(board)):
        if board[i] != 0 and board[i] != goal_board[i]:
            count += 1
    return count

# Core A* Search Function
def a_star_search(initial_board, goal_board):
    start_state = PuzzleState(initial_board, g=0)
    start_state.h = heuristic_misplaced_tiles(start_state.board, goal_board)

    frontier = []
    heapq.heappush(frontier, start_state)
    explored = set()

    while frontier:
        current_state = heapq.heappop(frontier)

        if current_state.board == tuple(goal_board):
            return current_state

        explored.add(current_state.board)

        for neighbor in current_state.get_neighbors():
            if neighbor.board in explored:
                continue

            neighbor.h = heuristic_misplaced_tiles(neighbor.board, goal_board)
            heapq.heappush(frontier, neighbor)

    return None

def print_solution_path(solution_node):
    path = []
    curr = solution_node
    while curr:
        path.append(curr)
        curr = curr.parent
    path.reverse()

    print(f"🎉 Goal reached in {len(path) - 1} moves!\n")
    for step, state in enumerate(path):
        print(f"Step {step}: Action taken -> {state.action} (g={state.g}, h={state.h}, f={state.f})")
        state.print_board()

