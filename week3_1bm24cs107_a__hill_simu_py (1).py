import math
import random

def get_conflicts(board):
    conflicts = 0
    n = len(board)
    for c1 in range(n):
        for c2 in range(c1 + 1, n):
            r1 = board[c1]
            r2 = board[c2]
            if r1 == r2:
                conflicts += 1
            elif abs(r1 - r2) == abs(c1 - c2):
                conflicts += 1
    return conflicts

def generate_neighbor(board):
    new_board = list(board)
    col = random.randint(0, 7)
    current_row = board[col]
    while True:
        new_row = random.randint(0, 7)
        if new_row != current_row:
            break
    new_board[col] = new_row
    return new_board, col, new_row

def print_chessboard(board):
    for row in range(8):
        line = ""
        for col in range(8):
            line += " Q " if board[col] == row else " . "
        print(line)
    print()

def simulated_annealing_8_queens():
    # Initial parameters from lab manual page 2
    current_board = [0, 1, 2, 3, 4, 5, 6, 7]
    T = 10.0
    alpha = 0.90

    current_cost = get_conflicts(current_board)

    print("==================================================")
    print("🔥 STARTING SIMULATED ANNEALING (8-QUEENS)")
    print("==================================================")
    print(f"Initial State: {current_board} | Cost: {current_cost} conflicts | Temp: {T}\n")

    iteration = 1
    # Loop continues until a solution is found or the temperature cools down completely
    while T > 0.0001 and current_cost > 0:
        proposed_board, col, new_row = generate_neighbor(current_board)
        proposed_cost = get_conflicts(proposed_board)
        delta_E = proposed_cost - current_cost

        # Only print details for the first 3 steps to keep output short and match the manual
        show_log = iteration <= 3

        if show_log:
            print(f"### Step {iteration}")
            print(f"Action: Randomly pick Column {col} and move queen to row {new_row}")
            print(f"Proposed Board: {proposed_board} | Proposed Cost: {proposed_cost}")
            print(f"Cost Difference: ΔE = {delta_E}")

        # Acceptance Check
        if delta_E < 0:
            current_board = proposed_board
            current_cost = proposed_cost
            if show_log:
                print("Decision: ACCEPT move immediately (improvement).")
        else:
            p = math.exp(-delta_E / T)
            r = random.random()
            if show_log:
                print(f"Acceptance Calculation: P = e^(-{delta_E} / {T:.2f}) ≈ {p:.3f}")
                print(f"Random Roll: R = {r:.2f}")

            if r < p:
                current_board = proposed_board
                current_cost = proposed_cost
                if show_log:
                    print("Decision: ACCEPT the worse move to escape local minima.")
            else:
                if show_log:
                    print("Decision: REJECT the move and revert board.")

        T = T * alpha
        if show_log:
            print(f"Temperature Update: T = {T:.2f}\n")
            if iteration == 3:
                print("... [Suppressing intermediate steps for clean output] ...\n")

        iteration += 1

    print("==================================================")
    print("📉 CONVERGENCE SUMMARY")
    print("==================================================")
    print(f"Final Board: {current_board}")
    print(f"Final Cost: {current_cost} (Solution Found)" if current_cost == 0 else f"Final Cost: {current_cost} conflicts")
    print("\nVisual Board Matrix:")
    print_chessboard(current_board)

if __name__ == "__main__":
    # Optional seed to reliably find a successful solution in a single run
    random.seed(42)
    simulated_annealing_8_queens()